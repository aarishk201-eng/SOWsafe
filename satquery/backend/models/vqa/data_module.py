def get_bigearthnet_datamodule():
    """Initializes and returns the official BENTxTDataModule with stratified subset filtering."""
    
    # Target the real LMDB directory generated by rico-hdl
    encoded_dir = os.path.join(os.path.dirname(__file__), "..", "..", "Encoded-BigEarthNet")
    os.makedirs(encoded_dir, exist_ok=True)
    
    backend_dir = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
    metadata_file = os.path.join(backend_dir, "BigEarthNet.txt", "BigEarthNet.txt.parquet")
    
    # If we generated a local geographic subset, use that instead of the 4.6M row parquet
    subset_parquet = os.path.join(backend_dir, "fixtures", "gee_subset", "subset.parquet")
    if os.path.exists(subset_parquet):
        metadata_file = subset_parquet
        
    dm = BENTxTDataModule(
        image_lmdb_file=encoded_dir,
        metadata_file=metadata_file,
        bands="S1S2-10m20m",
        img_size=120,
        batch_size=8,
        num_workers_dataloader=0, # Use 0 in windows/mock to avoid multiprocessing issues
        types=['binary', 'mcq', 'captioning', 'bounding box'],
        categories=None,
        countries=None,
        seasons=None,
        climate_zones=None,
        point_token=['<point>', '</point>'],
        ref_token=['<ref>', '</ref>'],
    )
    
    print("[DataModule] Setting up BENTxTDataModule...")
    dm.setup()
    print("[DataModule] Setup complete.")
    return dm
